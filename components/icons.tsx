export const ICON_NAMES = Object.keys(ICONS).sort();

export function getIcon(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || Star;
}

/**
 * Renders an icon chosen at runtime. `createElement` is used rather than
 * assigning the looked-up component to a capitalized local, which would count
 * as defining a component during render.
 */
export function IconView({ name, ...props }: { name?: string } & LucideProps) {
  return createElement(getIcon(name), props);
}
